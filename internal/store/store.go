// SaveResult tells what SaveBatch stored.
type SaveResult struct {
	New int // messages new to the archive
	// Skipped counts messages deleted by retention that were not archived
	// again, because they would already be expired in this folder.
	Skipped int
}

// SaveBatch stores message metadata and locations for a batch and advances
// the folder's last UID, all in one transaction, in the order of the
// hashes (sortBatch). A message deleted by
// retention is stored again only where it would not already be expired;
// otherwise it is skipped and its file scheduled for removal. The caller
// holds the blob lock (sync and import take it for the whole run), so the
// transaction takes only the attestation fence.
func (s *Store) SaveBatch(ctx context.Context, folderID int64, lastUID uint32, metas []MessageMeta, locs []Location) (SaveResult, error) {
	return s.saveBatch(ctx, folderID, lastUID, metas, locs, nil)
}

// saveBatch is SaveBatch; after, if set, runs last in the same transaction
// with what the batch stored.
func (s *Store) saveBatch(ctx context.Context, folderID int64, lastUID uint32, metas []MessageMeta, locs []Location,
	after func(*db.Queries, SaveResult) error) (SaveResult, error) {
	metas, locs = sortBatch(metas, locs)
	var res SaveResult
	err := s.inWriteTx(ctx, false, func(q *db.Queries) error {
		res = SaveResult{}
		skip, err := skipDeleted(ctx, q, folderID, metas, locs)
		if err != nil {
			return err
		}
		for i := range metas {
			m := &metas[i]
			if skip[m.SHA256] {
				res.Skipped++
				continue
			}
			n, err := q.InsertMessage(ctx, insertMessageParams(m))
			if err != nil {
				return fmt.Errorf("insert message %s: %w", m.SHA256, err)
			}
			res.New += int(n)

			l := locs[i]
			flags := l.Flags
			if flags == nil {
				flags = []string{}
			}
			var internal *time.Time
			if !l.InternalDate.IsZero() {
				internal = &l.InternalDate
			}
			err = q.UpsertLocation(ctx, db.UpsertLocationParams{
				MessageSha256: m.SHA256, FolderID: l.FolderID,
				Uidvalidity: int64(l.UIDValidity), Uid: int64(l.UID),
				Flags: flags, InternalDate: internal,
			})
			if err != nil {
				return fmt.Errorf("insert location: %w", err)
			}
		}
		if err := q.AdvanceFolder(ctx, db.AdvanceFolderParams{ID: folderID, LastUid: int64(lastUID)}); err != nil {
			return err
		}
		if after != nil {
			return after(q, res)
		}
		return nil
	})
	if err != nil {
		return SaveResult{}, err
	}
	return res, nil
}

// skipDeleted returns the hashes of a batch to skip: messages deleted by
// retention (a tombstone and no row) that would already be expired in the
// folder, and that no hold covers there. Their files are scheduled for
// removal at once. A message not skipped is archived again, as if this
// location had existed when it was deleted.
func skipDeleted(ctx context.Context, q *db.Queries, folderID int64, metas []MessageMeta, locs []Location) (map[string]bool, error) {
	shas := make([]string, len(metas))
	for i := range metas {
		shas[i] = metas[i].SHA256
	}
	deleted, err := q.TombstonedOf(ctx, shas)
	if err != nil || len(deleted) == 0 {
		return nil, err
	}
	archivedAt := make(map[string]time.Time, len(deleted))
	for _, d := range deleted {
		archivedAt[d.Sha256] = d.ArchivedAt
	}
	skip := map[string]bool{}
	var remove []string
	for i := range metas {
		at, ok := archivedAt[metas[i].SHA256]
		if !ok {
			continue
		}
		var internal *time.Time
		if !locs[i].InternalDate.IsZero() {
			internal = &locs[i].InternalDate
		}
		yes, err := q.SkipRearchive(ctx, db.SkipRearchiveParams{FolderID: folderID, SentAt: metas[i].SentAt, InternalDate: internal, ArchivedAt: at})
		if err != nil {
			return nil, err
		}
		if yes && !skip[metas[i].SHA256] {
			skip[metas[i].SHA256] = true
			remove = append(remove, metas[i].SHA256)
		}
	}
	if len(remove) > 0 {
		if err := q.ScheduleBlobRemovals(ctx, db.ScheduleBlobRemovalsParams{Shas: remove, DueAt: time.Now()}); err != nil {
			return nil, err
		}
	}
	return skip, nil
}

func insertMessageParams(m *MessageMeta) db.InsertMessageParams {
	return db.InsertMessageParams{
		Sha256: m.SHA256, Size: m.Size, MessageID: m.MessageID, Subject: m.Subject,
		FromAddr: m.From, SentAt: m.SentAt, StoredPath: m.StoredPath, BodyText: m.BodyText,
		ToAddr: m.To, CcAddr: m.Cc, AttachmentNames: m.attachmentNames(), HasAttachment: m.HasAttachment,
		InReplyTo: m.InReplyTo, ReferenceIds: m.referenceIDs(), ThreadID: m.ThreadID, IndexVersion: IndexVersion,
	}
}

// TouchFolder marks a folder as synced without new messages.
func (s *Store) TouchFolder(ctx context.Context, folderID int64) error {
	return one(s.q.TouchFolder(ctx, folderID))
}

// SyncRun records the outcome of syncing one account.
type SyncRun struct {
	ID              int64
	AccountID       int64
	Status          string
	MessagesFetched int
	MessagesNew     int
	Error           string
	Reconcile       ReconcileCounts
	// Health is how the run changes the account's failure streak.
	Health HealthEffect
	// LossAlert, if set, is stored for the notifier with the run.
	LossAlert *LossAlert
}

// LossAlertMaxAge is how long a loss alert waits to be sent. Older ones are
// given up, so that a webhook configured later never sends old losses.
const LossAlertMaxAge = 24 * time.Hour

// StartSyncRun creates a running sync record. Call it while holding the
// account's sync lock: it closes runs left open by a process that died.
func (s *Store) StartSyncRun(ctx context.Context, accountID int64) (*SyncRun, error) {
	if _, err := s.q.FailStaleSyncRuns(ctx, accountID); err != nil {
		return nil, err
	}
	id, err := s.q.StartSyncRun(ctx, accountID)
	if err != nil {
		return nil, err
	}
	return &SyncRun{ID: id, AccountID: accountID, Status: "running"}, nil
}

// FinishSyncRun stores the final state of a sync run and, in the same
// transaction, its effect on the account's failure streak.
func (s *Store) FinishSyncRun(ctx context.Context, r *SyncRun) error {
	return s.inTx(ctx, func(q *db.Queries) error {
		err := one(q.FinishSyncRun(ctx, db.FinishSyncRunParams{
			ID: r.ID, Status: r.Status, Error: r.Error,
			MessagesFetched:   clampInt32(r.MessagesFetched),
			MessagesNew:       clampInt32(r.MessagesNew),
			ReconciledFolders: clampInt32(r.Reconcile.Folders),
			LocationsGone:     clampInt32(r.Reconcile.Gone),
			LocationsBack:     clampInt32(r.Reconcile.Back),
			FlagsChanged:      clampInt32(r.Reconcile.FlagsChanged),
		}))
		if err != nil {
			return err
		}
		if r.LossAlert != nil {
			if err := insertLossAlert(ctx, q, r.AccountID, r.ID, r.LossAlert); err != nil {
				return err
			}
		}
		// Runs happen without a webhook too: keep unsent alerts from piling
		// up in the pending index.
		if _, err := q.ExpireLossAlerts(ctx, LossAlertMaxAge.Seconds()); err != nil {
			return err
		}
		switch r.Health {
		case HealthSuccess:
			return q.RecordSyncSuccess(ctx, r.AccountID)
		case HealthFailure:
			return q.RecordSyncFailure(ctx, r.AccountID)
		}
		return nil
	})
}

// UpdateSyncRunProgress stores the counters of a running sync.
func (s *Store) UpdateSyncRunProgress(ctx context.Context, r *SyncRun) error {
	return s.q.UpdateSyncRunProgress(ctx, db.UpdateSyncRunProgressParams{
		ID: r.ID, MessagesFetched: clampInt32(r.MessagesFetched), MessagesNew: clampInt32(r.MessagesNew),
	})
}

// LastRun is the most recent sync run of an account.
type LastRun struct {
	StartedAt       time.Time
	FinishedAt      *time.Time
	Status          string
	MessagesFetched int
	MessagesNew     int
	Error           string
	Reconcile       ReconcileCounts
}

// LastRuns returns the most recent sync run per account ID.
func (s *Store) LastRuns(ctx context.Context) (map[int64]LastRun, error) {
	rows, err := s.q.LastSyncRuns(ctx)
	if err != nil {
		return nil, err
	}
	out := make(map[int64]LastRun, len(rows))
	for _, r := range rows {
		out[r.AccountID] = LastRun{
			StartedAt: r.StartedAt, FinishedAt: r.FinishedAt, Status: r.Status,
			MessagesFetched: int(r.MessagesFetched), MessagesNew: int(r.MessagesNew), Error: deref(r.Error),
			Reconcile: ReconcileCounts{
				Folders: int(r.ReconciledFolders), Gone: int(r.LocationsGone),
				Back: int(r.LocationsBack), FlagsChanged: int(r.FlagsChanged),
			},
		}
	}
	return out, nil
}

// AccountStats summarizes the archive for one account.
type AccountStats struct {
	AccountID int64
	Account   string
	Kind      AccountKind
	OwnerID   *int64
	Enabled   bool
	CreatedAt time.Time
	RemovedAt *time.Time
	// SyncInterval is the account's own sync interval, as in Account.
	SyncInterval *time.Duration
	Folders      int
	// Messages counts distinct messages; one found in two folders of the
	// account counts once.
	Messages int64
	// Gone counts messages whose locations in this account are all gone
	// from the server.
	Gone             int64
	LastReconciledAt *time.Time
	LastRunAt        *time.Time
	LastStatus       *string
	LastRunError     *string
}

// Stats returns per-account statistics and the number of unique messages,
// for all accounts or, with owner set, for one user's accounts.
func (s *Store) Stats(ctx context.Context, owner *int64) ([]AccountStats, int64, error) {
	rows, err := s.q.AccountStats(ctx, owner)
	if err != nil {
		return nil, 0, err
	}
	lastRun, err := s.LastRuns(ctx)
	if err != nil {
		return nil, 0, err
	}
	out := make([]AccountStats, 0, len(rows))
	for _, r := range rows {
		st := AccountStats{AccountID: r.ID, Account: r.Name, Kind: AccountKind(r.Kind), OwnerID: r.OwnerID, Enabled: r.Enabled,
			CreatedAt: r.CreatedAt, RemovedAt: r.RemovedAt, SyncInterval: secondsToInterval(r.SyncIntervalSeconds),
			Folders: int(r.Folders), Messages: r.Messages, Gone: r.Gone, LastReconciledAt: r.LastReconciledAt}
		if run, ok := lastRun[r.ID]; ok {
			st.LastRunAt, st.LastStatus = &run.StartedAt, &run.Status
			if run.Error != "" {
				st.LastRunError = &run.Error
			}
		}
		out = append(out, st)
	}
	var unique int64
	if owner == nil {
		unique, err = s.q.CountMessages(ctx)
	} else {
		unique, err = s.q.CountOwnedMessages(ctx, owner)
	}
	return out, unique, err
}

// GetMessage returns the metadata of one archived message.
func (s *Store) GetMessage(ctx context.Context, sha256 string) (*MessageMeta, error) {
	r, err := s.q.GetMessage(ctx, sha256)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return &MessageMeta{
		SHA256: r.Sha256, Size: r.Size, MessageID: deref(r.MessageID), Subject: deref(r.Subject),
		From: deref(r.FromAddr), SentAt: r.SentAt, StoredPath: r.StoredPath,
	}, nil
}

// one turns the result of an :execrows query that targets a single row
// into ErrNotFound when no row matched.
func one(rows int64, err error) error {
	if err != nil {
		return err
	}
	if rows == 0 {
		return ErrNotFound
	}
	return nil
}

func clampInt32(n int) int32 {
	return int32(min(n, math.MaxInt32)) //nolint:gosec // clamped
}

func deref(s *string) string {
	if s == nil {
		return ""
	}
	return *s
}
