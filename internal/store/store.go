//go:embed migrations/*.sql
var migrationsFS embed.FS

// ErrNotFound is returned when a record does not exist.
var ErrNotFound = errors.New("not found")

// ErrConflict is returned when a unique constraint is violated.
var ErrConflict = errors.New("already exists")

// ErrNoServer is returned for changes that only IMAP accounts allow, such
// as syncing or setting a server, folders or a password.
var ErrNoServer = errors.New("import and smtp accounts have no server: they are not synced, and their server, folders and password cannot be set")

// Store wraps a PostgreSQL connection pool. Queries are generated by sqlc
// from internal/store/queries (see sqlc.yaml).
type Store struct {
	pool       *pgxpool.Pool
	q          *db.Queries
	userAgents userAgentCache
	// blobWait holds the wait slots for the blob lock (blobWaitSlot), and
	// blobParked counts the writers waiting for one.
	blobWait   chan struct{}
	blobParked atomic.Int32
	// gooseLockWait is called when Migrate or MigrateDown has to wait
	// for goose's lock (see SetGooseLockWait).
	gooseLockWait func(GooseLockHolder)
}

// Option configures Open.
type Option func(*openConfig)

type openConfig struct {
	// settings are the SET statements run on every new connection.
	settings []string
	// tracer is the pgx query tracer of every connection; only tests set
	// it.
	tracer pgx.QueryTracer
	// dial replaces the dialer of every connection; only tests set it.
	dial pgconn.DialFunc
}

// ForMigrations sets up the store for `migrate` and `migrate down`, so
// that a statement of a killed command does not run on for long and keep
// goose's lock (#253). Every new connection of the pool gets:
//
//   - client_connection_check_interval = 10s: PostgreSQL 14 and later on
//     Linux check every 10 s during a running statement whether the client
//     is still there, and abort the statement about 10 s after its socket
//     closed (SIGKILL, a crashed container). Without it, the server notices
//     only when the statement ends.
//   - TCP keepalives (idle 60 s, then every 10 s, 6 probes): if the client's
//     host or network vanishes and no FIN arrives, the server notices after
//     about 2 minutes instead of the kernel default of about 2 hours. They
//     apply to TCP connections only; PostgreSQL ignores them on a Unix
//     socket.
//
// Each SET is best effort: its error is ignored, so a server or proxy that
// refuses one (PostgreSQL before 14, a platform without the check, a
// pooler) works as before, just without that setting.
func ForMigrations() Option {
	return withCheckInterval("10s")
}

// withCheckInterval is ForMigrations with another client connection check
// interval, for tests.
func withCheckInterval(interval string) Option {
	return func(c *openConfig) {
		c.settings = append(c.settings,
			"SET client_connection_check_interval = '"+interval+"'",
			"SET tcp_keepalives_idle = 60",
			"SET tcp_keepalives_interval = 10",
			"SET tcp_keepalives_count = 6",
		)
	}
}

// Open connects to the database.
func Open(ctx context.Context, url string, opts ...Option) (*Store, error) {
	var oc openConfig
	for _, o := range opts {
		o(&oc)
	}
	cfg, err := pgxpool.ParseConfig(url)
	if err != nil {
		return nil, err
	}
	if settings := oc.settings; len(settings) > 0 {
		cfg.AfterConnect = func(ctx context.Context, conn *pgx.Conn) error {
			for _, set := range settings {
				// Best effort (see ForMigrations): a refused SET is
				// ignored. Only a connection that broke on the way is
				// not handed out.
				if _, err := conn.Exec(ctx, set); err != nil && conn.IsClosed() {
					return err
				}
			}
			return nil
		}
	}
	if oc.tracer != nil {
		cfg.ConnConfig.Tracer = oc.tracer
	}
	if oc.dial != nil {
		cfg.ConnConfig.DialFunc = oc.dial
	}
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		return nil, err
	}
	if err := pool.Ping(ctx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("connect to database: %w", err)
	}
	return &Store{pool: pool, q: db.New(pool), blobWait: make(chan struct{}, blobWaiters)}, nil
}

// SetGooseLockWait sets the function that Migrate and MigrateDown call
// once when goose's lock is held by another session, before they wait for
// it (see gooseLocker). It gets the session that holds the lock. Call it
// before Migrate or MigrateDown, not while one runs.
func (s *Store) SetGooseLockWait(onWait func(GooseLockHolder)) {
	s.gooseLockWait = onWait
}

// Close releases all connections.
func (s *Store) Close() { s.pool.Close() }

// Migrate rebuilds the indexes if the database needs it (see
// RebuildIndexesIfNeeded) and then applies all pending schema migrations.
// The rebuild runs first because pending migrations would already write
// through misordered indexes. If it fails, nothing is migrated. The
// migrations run under goose's migration lock (withMigrations).
func (s *Store) Migrate(ctx context.Context) ([]string, error) {
	if _, err := s.RebuildIndexesIfNeeded(ctx, nil); err != nil {
		return nil, err
	}
	var applied []string
	err := s.withMigrations(ctx, true, func(p *goose.Provider) error {
		results, err := p.Up(ctx)
		for _, r := range results {
			applied = append(applied, r.Source.Path)
		}
		return err
	})
	return applied, err
}

// MigrateDown rolls back the most recently applied migration. This usually
// drops data. It returns the migration that was rolled back. It runs under
// goose's migration lock, as Migrate does.
func (s *Store) MigrateDown(ctx context.Context) (string, error) {
	var rolledBack string
	err := s.withMigrations(ctx, true, func(p *goose.Provider) error {
		r, err := p.Down(ctx)
		if errors.Is(err, goose.ErrNoNextVersion) {
			return errors.New("no migration to roll back")
		}
		if err != nil {
			return err
		}
		rolledBack = r.Source.Path
		return nil
	})
	return rolledBack, err
}

// MigrationStatus describes one known migration.
type MigrationStatus struct {
	Path      string
	Applied   bool
	AppliedAt time.Time
}

// MigrationStatus lists all migrations and whether they are applied. It
// does not wait for a running migration: it reads goose_db_version without
// the migration lock and sees the migrations committed so far.
func (s *Store) MigrationStatus(ctx context.Context) ([]MigrationStatus, error) {
	var out []MigrationStatus
	err := s.withMigrations(ctx, false, func(p *goose.Provider) error {
		statuses, err := p.Status(ctx)
		if err != nil {
			return err
		}
		for _, st := range statuses {
			out = append(out, MigrationStatus{
				Path:      st.Source.Path,
				Applied:   st.State == goose.StateApplied,
				AppliedAt: st.AppliedAt,
			})
		}
		return nil
	})
	return out, err
}

// withMigrations runs fn with a goose provider for the embedded migrations.
// With locked, the provider takes goose's session lock (a single bigint
// advisory lock, lock.DefaultLockID) for each Up or Down, on the
// connection that runs the migrations, so that two migrations at the same
// time never apply the same version. The second waits without a time limit
// and says so (gooseLocker). Status reads go without it, because goose's
// Status takes the lock too and would wait behind a running migration.
//
// goose runs on a short-lived pgx pool of its own, made from a copy of
// the store's pool config (the same server, credentials, ForMigrations
// settings and tracer) and closed before withMigrations returns. So each
// call opens one extra short-lived connection, and goose never takes
// connections from the store's pool. This keeps goose's lock out of the
// store's pool (#269): when database/sql gives up goose's *sql.Conn after
// a cancel (a bare driver.ErrBadConn, see discardConn), the stdlib driver
// releases the pgx connection to its pool instead of closing it, and the
// connection may still hold goose's lock. The teardown frees that lock:
// see closeMigrationPool.
//
// When ctx has ended, the error wraps ctx's error (withCtxErr), whichever
// step of goose saw the cancel.
func (s *Store) withMigrations(ctx context.Context, locked bool, fn func(*goose.Provider) error) error {
	sub, err := fs.Sub(migrationsFS, "migrations")
	if err != nil {
		return err
	}
	var opts []goose.ProviderOption
	if locked {
		opts = append(opts, goose.WithSessionLocker(gooseLocker{onWait: s.gooseLockWait}))
	}
	// The copy keeps the store's pool_min_conns and pool_min_idle_conns;
	// zeroed, goose's pool opens only the connections goose asks for
	// (#277), not idle ones in the background on ctx.
	cfg := s.pool.Config()
	cfg.MinConns = 0
	cfg.MinIdleConns = 0
	gp, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		return withCtxErr(ctx, err)
	}
	sqlDB := stdlib.OpenDBFromPool(gp)
	defer closeMigrationPool(ctx, gp, sqlDB)
	provider, err := goose.NewProvider(goose.DialectPostgres, sqlDB, sub, opts...)
	if err != nil {
		return err
	}
	return withCtxErr(ctx, fn(provider))
}

// migrationPoolUnlockLimit bounds the teardown unlock of
// closeMigrationPool, so that a vanished server cannot hang it.
const migrationPoolUnlockLimit = 5 * time.Second

// closeMigrationPool closes goose's pool gp and its database/sql handle
// sqlDB, and frees goose's lock if a connection of gp still holds it.
//
// Closing sqlDB releases its connections to gp. A connection that
// database/sql gave up while it held goose's lock is already back in gp:
// pgxpool keeps it when it is open and idle (outside a transaction), and
// destroys it otherwise. On every idle connection the teardown runs
// pg_advisory_unlock_all(), so goose's lock of such an idle connection is
// free when Migrate or MigrateDown returns. A destroyed connection (for
// example one given up inside goose's transaction) keeps its lock until
// its backend exits, which the server notices asynchronously; gp.Close
// waits for pgx's close of it. The unlock only touches sessions of gp; the
// command lock (LockMigrations) is on a connection of its own.
//
// The unlock runs without ctx's cancel, so a Ctrl-C does not skip it, and
// within migrationPoolUnlockLimit. A failed or timed-out unlock is ignored:
// gp.Close closes the connection anyway, and the server then frees the
// lock when the backend exits.
//
// Known race, not a leak: gp's background health check also takes idle
// connections for a moment. If it holds the connection with goose's lock
// exactly while AcquireAllIdle runs, that connection is skipped here, and
// gp.Close frees the lock asynchronously instead.
func closeMigrationPool(ctx context.Context, gp *pgxpool.Pool, sqlDB *sql.DB) {
	_ = sqlDB.Close()
	uctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), migrationPoolUnlockLimit)
	defer cancel()
	for _, c := range gp.AcquireAllIdle(uctx) {
		_, _ = c.Exec(uctx, "SELECT pg_advisory_unlock_all()")
		c.Release()
	}
	gp.Close()
}

// withCtxErr returns err so that it wraps ctx's error when ctx has ended
// (#268), keeping err's text: "context canceled (<err>)". A nil err stays
// nil, so a migration that finished just before the cancel still reports
// success, and an err that already wraps ctx's error is returned as is.
//
// It is needed because a cancel can lose ctx's error on goose's *sql.Conn:
// when ctx ends after pgx started a query but before it sent it, pgconn's
// context-already-done error is safe to retry, and pgx's stdlib driver
// turns every such error into a bare driver.ErrBadConn. goose then appends
// the "sql: connection is already closed" of its own cleanup.
func withCtxErr(ctx context.Context, err error) error {
	if err == nil {
		return nil
	}
	if cerr := ctx.Err(); cerr != nil && !errors.Is(err, cerr) {
		return fmt.Errorf("%w (%w)", cerr, err)
	}
	return err
}

// TLSMode describes how to secure the IMAP connection.
type TLSMode string

// Supported TLS modes.
const (
	TLSModeTLS      TLSMode = "tls"      // implicit TLS (port 993)
	TLSModeSTARTTLS TLSMode = "starttls" // STARTTLS upgrade (port 143)
	TLSModeNone     TLSMode = "none"     // plaintext, only for local testing
)

// AccountKind tells where an account's mail comes from.
type AccountKind string

// Account kinds.
const (
	// KindIMAP accounts are synced from an IMAP server.
	KindIMAP AccountKind = "imap"
	// KindImport accounts hold mail imported from files. They have no
	// server, login or password and are never enabled or synced.
	KindImport AccountKind = "import"
	// KindSMTP accounts receive copies of every message from a mail server
	// over SMTP (journaling). They have no server, login or password and
	// are never synced, but can be enabled and disabled.
	KindSMTP AccountKind = "smtp"
)

// HasServer reports whether the account is synced from an IMAP server.
func (k AccountKind) HasServer() bool { return k == KindIMAP }

// Account is an IMAP mailbox to archive, or mail imported from files.
type Account struct {
	ID              int64
	Kind            AccountKind
	Name            string
	Host            string
	Port            int
	TLSMode         TLSMode
	Username        string
	PasswordEnc     []byte
	IncludedFolders []string // empty means all folders
	ExcludedFolders []string
	Enabled         bool
	CreatedAt       time.Time
	// RemovedAt is set for removed accounts: their archived mail stays, but
	// they have no password and are never synced.
	RemovedAt *time.Time
	// OwnerID is the user who sees the account and its mail. It is nil only
	// before the first user exists; that user then gets the account.
	OwnerID *int64
	// Version increases with every change; see UpdateAccount.
	Version int64
	// SyncInterval is the account's own sync interval: nil uses the
	// server's, 0 keeps it off the schedule. Only IMAP accounts have one.
	SyncInterval *time.Duration
}

// secondsToInterval and intervalToSeconds convert the stored own sync
// interval (whole seconds, NULL for the server's).
func secondsToInterval(s *int32) *time.Duration {
	if s == nil {
		return nil
	}
	d := time.Duration(*s) * time.Second
	return &d
}

func intervalToSeconds(d *time.Duration) *int32 {
	if d == nil {
		return nil
	}
	s := int32(min(*d/time.Second, 1<<31-1)) //nolint:gosec // clamped
	return &s
}

func accountFromDB(r db.Account) *Account {
	return &Account{
		ID:              r.ID,
		Kind:            AccountKind(r.Kind),
		Name:            r.Name,
		Host:            r.Host,
		Port:            int(r.Port),
		TLSMode:         TLSMode(r.TlsMode),
		Username:        r.Username,
		PasswordEnc:     r.PasswordEnc,
		IncludedFolders: r.IncludedFolders,
		ExcludedFolders: r.ExcludedFolders,
		Enabled:         r.Enabled,
		CreatedAt:       r.CreatedAt,
		RemovedAt:       r.RemovedAt,
		OwnerID:         r.OwnerID,
		Version:         r.Version,
		SyncInterval:    secondsToInterval(r.SyncIntervalSeconds),
	}
}

// CreateAccount inserts a new account and sets its ID.
func (s *Store) CreateAccount(ctx context.Context, a *Account) error {
	return s.inTx(ctx, func(q *db.Queries) error {
		return createAccount(ctx, q, a)
	})
}

// CreateAccountSealed inserts a new account whose password is encrypted with
// its ID: seal gets the new ID and returns the encrypted password. Both
// happen in one transaction.
func (s *Store) CreateAccountSealed(ctx context.Context, a *Account, seal func(id int64) ([]byte, error)) error {
	return s.inTx(ctx, func(q *db.Queries) error {
		a.PasswordEnc = []byte{}
		if err := createAccount(ctx, q, a); err != nil {
			return err
		}
		enc, err := seal(a.ID)
		if err != nil {
			return err
		}
		a.PasswordEnc = enc
		return one(q.UpdatePassword(ctx, db.UpdatePasswordParams{ID: a.ID, PasswordEnc: enc}))
	})
}

func createAccount(ctx context.Context, q *db.Queries, a *Account) error {
	if a.IncludedFolders == nil {
		a.IncludedFolders = []string{}
	}
	if a.ExcludedFolders == nil {
		a.ExcludedFolders = []string{}
	}
	if a.Kind == "" {
		a.Kind = KindIMAP
	}
	switch {
	case a.Kind == KindIMAP && (a.Port < 1 || a.Port > 65535):
		return fmt.Errorf("invalid port %d", a.Port)
	case a.Kind == KindImport && (a.Port != 0 || a.Enabled || a.Host != "" || a.Username != ""):
		return errors.New("an import account has no server and is never enabled")
	case a.Kind == KindSMTP && (a.Port != 0 || a.Host != "" || a.Username != ""):
		return errors.New("an smtp account has no server")
	case a.Kind != KindIMAP && a.Kind != KindImport && a.Kind != KindSMTP:
		return fmt.Errorf("invalid account kind %q", a.Kind)
	case !a.Kind.HasServer() && a.SyncInterval != nil:
		return ErrNoServer
	}
	if !a.Kind.HasServer() {
		a.TLSMode = TLSModeNone // unused; the column needs a valid value
	}
	if a.PasswordEnc == nil {
		a.PasswordEnc = []byte{}
	}
	row, err := q.CreateAccount(ctx, db.CreateAccountParams{
		Name:                a.Name,
		Host:                a.Host,
		Port:                int32(a.Port), //nolint:gosec // range checked above
		TlsMode:             string(a.TLSMode),
		Username:            a.Username,
		PasswordEnc:         a.PasswordEnc,
		IncludedFolders:     a.IncludedFolders,
		ExcludedFolders:     a.ExcludedFolders,
		Enabled:             a.Enabled,
		OwnerID:             a.OwnerID,
		Kind:                string(a.Kind),
		SyncIntervalSeconds: intervalToSeconds(a.SyncInterval),
	})
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) && pgErr.Code == "23505" {
		return fmt.Errorf("account %q: %w", a.Name, ErrConflict)
	}
	if err != nil {
		return err
	}
	a.ID, a.CreatedAt, a.Version = row.ID, row.CreatedAt, row.Version
	fillAuditTarget(ctx, TargetAccount, a.ID)
	return nil
}

// GetAccount looks up an account by ID.
func (s *Store) GetAccount(ctx context.Context, id int64) (*Account, error) {
	r, err := s.q.GetAccount(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return accountFromDB(r), nil
}

// GetOwnedAccount looks up one of a user's accounts by name.
func (s *Store) GetOwnedAccount(ctx context.Context, owner int64, name string) (*Account, error) {
	r, err := s.q.GetOwnedAccount(ctx, db.GetOwnedAccountParams{OwnerID: &owner, Name: name})
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return accountFromDB(r), nil
}

// ListAccountsByName returns the accounts of all users with this name.
func (s *Store) ListAccountsByName(ctx context.Context, name string) ([]*Account, error) {
	return accountsFromDB(s.q.ListAccountsByName(ctx, name))
}

// ListOwnedAccounts returns a user's accounts ordered by name.
func (s *Store) ListOwnedAccounts(ctx context.Context, owner int64) ([]*Account, error) {
	return accountsFromDB(s.q.ListOwnedAccounts(ctx, &owner))
}

func accountsFromDB(rows []db.Account, err error) ([]*Account, error) {
	if err != nil {
		return nil, err
	}
	out := make([]*Account, 0, len(rows))
	for _, r := range rows {
		out = append(out, accountFromDB(r))
	}
	return out, nil
}

// CountOwnedAccounts returns the number of accounts per owner ID.
func (s *Store) CountOwnedAccounts(ctx context.Context) (map[int64]int64, error) {
	rows, err := s.q.CountOwnedAccounts(ctx)
	if err != nil {
		return nil, err
	}
	out := make(map[int64]int64, len(rows))
	for _, r := range rows {
		if r.OwnerID != nil {
			out[*r.OwnerID] = r.Accounts
		}
	}
	return out, nil
}

// ListAccounts returns the accounts of all users ordered by name.
func (s *Store) ListAccounts(ctx context.Context) ([]*Account, error) {
	return accountsFromDB(s.q.ListAccounts(ctx))
}

// Folder is the sync state of one IMAP folder.
type Folder struct {
	ID          int64
	AccountID   int64
	Name        string
	UIDValidity uint32
	LastUID     uint32
	// LastReconciledAt is nil until the folder was first reconciled.
	LastReconciledAt *time.Time
}

// GetOrCreateFolder returns the sync state for a folder, creating it if new.
func (s *Store) GetOrCreateFolder(ctx context.Context, accountID int64, name string) (*Folder, error) {
	r, err := s.q.GetOrCreateFolder(ctx, db.GetOrCreateFolderParams{AccountID: accountID, Name: name})
	if err != nil {
		return nil, err
	}
	return &Folder{
		ID: r.ID, AccountID: accountID, Name: name,
		UIDValidity:      uint32(r.Uidvalidity), //nolint:gosec // stored from uint32
		LastUID:          uint32(r.LastUid),     //nolint:gosec // stored from uint32
		LastReconciledAt: r.LastReconciledAt,
	}, nil
}

// SetFolderDelimiters records the hierarchy delimiters from a LIST answer,
// by folder name, for the account's folders that have a row. It returns
// how many changed.
func (s *Store) SetFolderDelimiters(ctx context.Context, accountID int64, delimiters map[string]string) (int64, error) {
	p := db.SetFolderDelimitersParams{AccountID: accountID}
	for name, d := range delimiters {
		p.Names = append(p.Names, name)
		p.Delimiters = append(p.Delimiters, d)
	}
	return s.q.SetFolderDelimiters(ctx, p)
}

// ResetFolder records a new UIDVALIDITY and restarts the folder from UID 0.
func (s *Store) ResetFolder(ctx context.Context, folderID int64, uidValidity uint32) error {
	return one(s.q.ResetFolder(ctx, db.ResetFolderParams{ID: folderID, Uidvalidity: int64(uidValidity)}))
}

