// inTx runs fn in a transaction. With an entry from WithAudit in ctx, the
// entry is written after fn succeeded, in the same transaction. The
// transaction runs on the pool, or on the dedicated connection of ctx
// (withConn); so do the user agent lookup before it and the creation of a
// missing audit partition after its rollback.
func (s *Store) inTx(ctx context.Context, fn func(*db.Queries) error) error {
	p, _ := ctx.Value(auditKey{}).(*pendingAudit)
	if p != nil && p.written {
		p = nil
	}
	var ua *int64
	if p != nil {
		var err error
		if ua, err = s.auditUserAgent(ctx, p.entry); err != nil {
			return fmt.Errorf("%w: %w", ErrAuditUnavailable, err)
		}
	}
	var begin interface {
		Begin(context.Context) (pgx.Tx, error)
	} = s.pool
	if c := connFrom(ctx); c != nil {
		begin = c
	}
	tx, err := begin.Begin(ctx)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback(ctx) }()
	q := s.q.WithTx(tx)
	if err := fn(q); err != nil {
		return err
	}
	if p != nil && p.skip {
		p.skip, p = false, nil
	}
	if p != nil {
		if err := insertAudit(ctx, q, p.entry, ua); err != nil {
			// A failed statement aborts the transaction, so no retry here:
			// create the partition for the next attempt.
			_ = tx.Rollback(ctx)
			if missingPartition(err) {
				_, _ = s.EnsureAuditPartitions(ctx, 1)
			}
			return fmt.Errorf("%w: %w", ErrAuditUnavailable, err)
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return err
	}
	if p != nil {
		p.written = true
	}
	return nil
}

// inWriteTx is inTx for every transaction that inserts into messages or
// message_deletions. It takes the attestation fence shared before fn runs,
// and with blobs the blob lock shared before that: the lock order is blob
// lock, fence, row locks, so a writer never waits for the fence while it
// holds a row lock. A test checks that every such insert runs in fn.
//
// The blob lock is tried first. While it is held exclusively, the
// transaction is rolled back before fn runs, which gives the connection
// back, and a second one waits for the lock with one of the wait slots
// (blobWaitSlot), so that at most blobWaiters writers keep a connection
// while they wait. The slot is freed as soon as the lock is granted, before
// the fence: a writer waiting for an attestation must not hold it.
func (s *Store) inWriteTx(ctx context.Context, blobs bool, fn func(*db.Queries) error) error {
	var release func() // the wait slot of the second attempt
	lockBlobs := func(q *db.Queries) error {
		if release == nil {
			ok, err := q.TryLockBlobsShared(ctx, blobLockClass)
			if err != nil {
				return fmt.Errorf("try the blob lock: %w", err)
			}
			if !ok {
				return errBlobsBusy
			}
			return nil
		}
		err := q.LockBlobsShared(ctx, blobLockClass)
		release()
		if err != nil {
			return fmt.Errorf("wait for the blob lock: %w", err)
		}
		return nil
	}
	attempt := func() error {
		return s.inTx(ctx, func(q *db.Queries) error {
			if blobs {
				if err := lockBlobs(q); err != nil {
					return err
				}
			}
			if err := q.LockFenceShared(ctx, attestFenceClass); err != nil {
				return fmt.Errorf("wait for the attestation fence: %w", err)
			}
			return fn(q)
		})
	}
	err := attempt()
	if !blobs || !errors.Is(err, errBlobsBusy) {
		return err
	}
	r, err := s.blobWaitSlot(ctx)
	if err != nil {
		return fmt.Errorf("wait for the blob lock: %w", err)
	}
	release = r
	defer release()
	return attempt()
}

// errBlobsBusy ends the first attempt of inWriteTx while the blob lock is
// held exclusively; it never leaves inWriteTx.
var errBlobsBusy = errors.New("blob lock busy")

func isNoRows(err error) bool { return errors.Is(err, pgx.ErrNoRows) }

func keepUsableAdmin(ctx context.Context, q *db.Queries, id int64) error {
	admins, err := q.LockUsableAdmins(ctx)
	if err != nil {
		return err
	}
	if len(admins) == 1 && admins[0] == id {
		return ErrLastAdmin
	}
	return nil
}
